import test from "node:test";
import assert from "node:assert/strict";
import {runBrowserDeliverySmoke} from "../src/browserDeliverySmoke.js";
test("all RTS controls, ES module imports, and authenticated stance commands deliver over HTTP",async()=>{
 const result=await runBrowserDeliverySmoke();
 assert.equal(result.htmlControls,20);
 assert.equal(result.servedModules,21);
 assert.equal(result.gltfSkins,12);
 assert.equal(result.authoredClips,3);
 assert.equal(result.rosterSmokeMeshes,36);
 assert.equal(result.factionRigProfiles,6);
 assert.equal(result.factionTextures,6);
 assert.equal(result.factionMeshes,60);
 assert.ok(result.factionTriangles>5000);
 assert.equal(result.servedMeshes,10);
 assert.ok(result.assetTriangles>1000);
 assert.equal(result.authenticatedBatch,true);
 assert.equal(result.anonymousRejected,true);
 assert.match(result.scope,/NOT real browser/);
});
